/** Keeps average and count consistent with the star distribution. */
function rating(distribution: RatingSummary['distribution']): RatingSummary {
  const count = distribution.reduce((a, b) => a + b, 0)
  const total = distribution.reduce((acc, n, i) => acc + n * (i + 1), 0)
  return { average: count === 0 ? 0 : Math.round((total / count) * 10) / 10, count, distribution }
}

